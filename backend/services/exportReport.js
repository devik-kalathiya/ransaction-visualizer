const PDFDocument = require("pdfkit");

/**
 * Streams a PDF report for one transaction run directly to the given
 * writable stream (typically the Express `res` object).
 *
 * @param {import('stream').Writable} stream
 * @param {object} txn - row from `transactions`
 * @param {object[]} events - rows from `transaction_events`, oldest first
 * @param {object[]} ops - rows from `transaction_operations`
 */
function streamTransactionPdf(stream, txn, events, ops) {
  const doc = new PDFDocument({ margin: 50 });
  doc.pipe(stream);

  doc.fontSize(20).text("TXN Studio - Transaction Report", { underline: true });
  doc.moveDown();

  doc.fontSize(12).text(`Transaction ID: ${txn.txn_code}`);
  doc.text(`Operation: ${txn.operation}`);
  doc.text(`Isolation level: ${txn.isolation}`);
  doc.text(`Scenario: ${txn.scenario}`);
  doc.text(`Final state: ${txn.current_state}`);
  doc.text(`Status: ${txn.status}`);
  doc.text(`Created: ${txn.created_at}`);
  doc.text(`Last updated: ${txn.updated_at}`);
  doc.moveDown();

  doc.fontSize(14).text("Operation buffer", { underline: true });
  doc.moveDown(0.5);
  ops.forEach((op) => {
    doc.fontSize(11).text(`${op.seq}. ${op.op_code}  -  ${op.op_status}`);
  });
  doc.moveDown();

  doc.fontSize(14).text("Execution timeline", { underline: true });
  doc.moveDown(0.5);
  events.forEach((ev) => {
    const line = ev.from_state
      ? `${ev.created_at}   ${ev.from_state} -> ${ev.to_state}`
      : `${ev.created_at}   ${ev.to_state}`;
    doc.fontSize(11).text(line);
    if (ev.note) {
      doc.fontSize(9).fillColor("#666666").text(`    ${ev.note}`);
      doc.fillColor("#000000");
    }
  });

  doc.moveDown();
  doc.fontSize(9).fillColor("#888888").text(
    "Generated by TXN Studio - DBMS Academic Project (Transaction State & Lifecycle Simulator).",
    { align: "left" }
  );

  doc.end();
}

function toJsonReport(txn, events, ops) {
  return {
    transaction: txn,
    operations: ops,
    timeline: events,
    generatedAt: new Date().toISOString(),
  };
}

module.exports = { streamTransactionPdf, toJsonReport };
